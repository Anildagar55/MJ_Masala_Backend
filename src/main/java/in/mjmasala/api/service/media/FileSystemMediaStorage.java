package in.mjmasala.api.service.media;

import in.mjmasala.api.config.AppProperties;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Optional;

/**
 * Stores uploads on the local filesystem.
 *
 * Two details that matter:
 *
 * - **The directory is created on first use**, so a fresh deploy does not need a manual
 *   step. In production it should be a mounted volume; a container's own filesystem is
 *   lost on redeploy, and with it every product photo.
 * - **Writes go to a temporary file and are then moved into place**, so a crash mid-write
 *   cannot leave a half-written image that the storefront would serve.
 */
@Service
public class FileSystemMediaStorage implements MediaStorage {

    private static final Logger log = LoggerFactory.getLogger(FileSystemMediaStorage.class);

    private final Path root;

    public FileSystemMediaStorage(AppProperties properties) {
        this.root = Path.of(properties.media().dir()).toAbsolutePath().normalize();
        log.info("Product images will be stored in {}", root);
    }

    @Override
    public String store(String filename, byte[] content) {
        Path target = resolve(filename);
        try {
            Files.createDirectories(root);
            Path temp = Files.createTempFile(root, "upload-", ".part");
            Files.write(temp, content);
            Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING,
                    StandardCopyOption.ATOMIC_MOVE);
            return filename;
        } catch (IOException e) {
            throw new IllegalStateException("Could not store " + filename, e);
        }
    }

    @Override
    public Optional<byte[]> read(String filename) {
        Path file = resolve(filename);
        if (!Files.isReadable(file)) return Optional.empty();
        try {
            return Optional.of(Files.readAllBytes(file));
        } catch (IOException e) {
            log.warn("Could not read {}", filename, e);
            return Optional.empty();
        }
    }

    @Override
    public void delete(String filename) {
        if (filename == null || filename.isBlank()) return;
        try {
            Files.deleteIfExists(resolve(filename));
        } catch (IOException e) {
            // a file we cannot delete is not worth failing the request over
            log.warn("Could not delete {}", filename, e);
        }
    }

    /**
     * Resolves a name inside the media directory, refusing anything that escapes it.
     *
     * Filenames are generated by this application and never come from a client, but a path
     * traversal here would read or overwrite arbitrary files, so it is checked anyway.
     */
    private Path resolve(String filename) {
        Path resolved = root.resolve(filename).normalize();
        if (!resolved.startsWith(root)) {
            throw new IllegalArgumentException("Refusing a path outside the media directory: " + filename);
        }
        return resolved;
    }
}
